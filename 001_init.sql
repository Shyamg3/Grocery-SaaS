-- 001_init.sql  |  Multi-tenant shop billing + inventory (Supabase / Postgres)
-- Run in Supabase SQL editor, or save as supabase/migrations/001_init.sql
-- Principles: every row belongs to a shop (shop_id); RLS isolates shops;
-- bills are created ONLY through create_bill() so stock/totals can't drift.

create extension if not exists pg_trgm;

-- ---------- enums ----------
create type shop_role as enum ('owner', 'manager', 'cashier');
create type payment_mode as enum ('cash', 'upi', 'card', 'credit');
create type bill_status as enum ('active', 'void');
create type stock_move_type as enum ('opening', 'purchase', 'sale', 'adjustment', 'return');

-- ---------- helpers ----------
create or replace function set_updated_at() returns trigger
language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

-- ---------- tenants ----------
create table shops (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  shop_type text not null default 'grocery',      -- grocery, general, stationery, fancy...
  language text not null default 'ta',            -- UI language
  currency text not null default 'INR',
  gstin text,
  settings jsonb not null default '{}',           -- anything shop-specific
  created_at timestamptz not null default now()
);

create table shop_members (
  shop_id uuid not null references shops(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role shop_role not null default 'owner',
  primary key (shop_id, user_id)
);

-- security definer so policies can call it without recursion
create or replace function is_shop_member(p_shop uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from shop_members
    where shop_id = p_shop and user_id = (select auth.uid())
  );
$$;

create table shop_counters (
  shop_id uuid primary key references shops(id) on delete cascade,
  last_bill_no bigint not null default 0
);

-- ---------- catalog ----------
create table products (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references shops(id) on delete cascade,
  name text not null,
  name_ta text,
  aliases text[] not null default '{}',           -- "arisi", "rice", local names for voice matching
  unit text not null default 'pcs',               -- kg, g, l, ml, pcs, pack
  sell_price numeric(12,2) not null check (sell_price >= 0),
  cost_price numeric(12,2) check (cost_price >= 0),
  stock_qty numeric(14,3) not null default 0,     -- may go negative (shops sell first, fix later)
  reorder_level numeric(14,3) not null default 0,
  barcode text,
  tax_rate numeric(5,2) not null default 0,
  custom_fields jsonb not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index products_shop_idx on products(shop_id);
create index products_name_trgm on products using gin (name gin_trgm_ops);
create unique index products_barcode_uq on products(shop_id, barcode) where barcode is not null;
create trigger products_updated before update on products
  for each row execute function set_updated_at();

create table customers (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references shops(id) on delete cascade,
  name text not null,
  phone text,
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index customers_shop_idx on customers(shop_id);

-- ---------- sales ----------
create table bills (
  id uuid primary key,                            -- generated by the client => safe retries when offline
  shop_id uuid not null references shops(id) on delete cascade,
  bill_no bigint not null,
  customer_id uuid references customers(id),
  payment_mode payment_mode not null default 'cash',
  subtotal numeric(12,2) not null default 0,
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0,
  status bill_status not null default 'active',
  source text not null default 'manual',          -- manual | voice | photo
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique (shop_id, bill_no)
);
create index bills_shop_date_idx on bills(shop_id, created_at desc);

create table bill_items (
  id uuid primary key default gen_random_uuid(),
  bill_id uuid not null references bills(id) on delete cascade,
  shop_id uuid not null references shops(id) on delete cascade,
  product_id uuid references products(id),
  product_name text not null,                     -- snapshot: name at time of sale
  qty numeric(14,3) not null check (qty > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) not null
);
create index bill_items_bill_idx on bill_items(bill_id);
create index bill_items_shop_product_idx on bill_items(shop_id, product_id);

create table stock_movements (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references shops(id) on delete cascade,
  product_id uuid not null references products(id),
  move_type stock_move_type not null,
  qty_change numeric(14,3) not null,              -- negative for sales
  ref_bill_id uuid references bills(id),
  note text,
  created_at timestamptz not null default now()
);
create index stock_moves_idx on stock_movements(shop_id, product_id, created_at desc);

create table credit_ledger (                       -- udhaar
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references shops(id) on delete cascade,
  customer_id uuid not null references customers(id),
  amount numeric(12,2) not null,                  -- + = customer owes more, - = customer paid
  ref_bill_id uuid references bills(id),
  note text,
  created_at timestamptz not null default now()
);
create index credit_ledger_idx on credit_ledger(shop_id, customer_id);

-- voice quality tracking: lets you measure and improve accuracy with real data
create table voice_events (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references shops(id) on delete cascade,
  transcript text,
  parsed jsonb,                                   -- what the AI understood
  final_items jsonb,                              -- what the owner confirmed after editing
  created_at timestamptz not null default now()
);

