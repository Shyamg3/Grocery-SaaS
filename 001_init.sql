-- ---------- RPC: create a shop and make the caller its owner ----------
create or replace function create_shop(p_name text, p_shop_type text default 'grocery')
returns uuid language plpgsql security definer set search_path = public as $$
declare v_id uuid;
begin
  if (select auth.uid()) is null then raise exception 'not authenticated'; end if;
  insert into shops(name, shop_type) values (p_name, p_shop_type) returning id into v_id;
  insert into shop_members(shop_id, user_id, role) values (v_id, (select auth.uid()), 'owner');
  insert into shop_counters(shop_id) values (v_id);
  return v_id;
end $$;

-- ---------- RPC: atomic, idempotent bill creation ----------
-- p_items example: [{"product_id":"...","qty":2,"unit_price":55}]
-- Runs as the caller (security invoker), so RLS still applies.
create or replace function create_bill(
  p_bill_id uuid,
  p_shop_id uuid,
  p_items jsonb,
  p_customer_id uuid default null,
  p_payment payment_mode default 'cash',
  p_discount numeric default 0,
  p_source text default 'manual',
  p_created_at timestamptz default now()
) returns uuid language plpgsql as $$
declare
  v_bill_no bigint;
  v_item jsonb;
  v_qty numeric;
  v_price numeric;
  v_line numeric;
  v_subtotal numeric := 0;
  v_pid uuid;
  v_name text;
begin
  -- idempotency: a retried offline sync returns the same bill, never a duplicate
  if exists (select 1 from bills where id = p_bill_id) then
    return p_bill_id;
  end if;

  if jsonb_array_length(p_items) = 0 then
    raise exception 'bill must have at least one item';
  end if;

  update shop_counters set last_bill_no = last_bill_no + 1
   where shop_id = p_shop_id returning last_bill_no into v_bill_no;
  if v_bill_no is null then raise exception 'shop not found or no access'; end if;

  insert into bills(id, shop_id, bill_no, customer_id, payment_mode, discount, source, created_by, created_at)
  values (p_bill_id, p_shop_id, v_bill_no, p_customer_id, p_payment, p_discount, p_source,
          (select auth.uid()), p_created_at);

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_pid   := (v_item->>'product_id')::uuid;
    v_qty   := (v_item->>'qty')::numeric;
    v_price := (v_item->>'unit_price')::numeric;
    v_line  := round(v_qty * v_price, 2);

    select name into v_name from products where id = v_pid and shop_id = p_shop_id;
    if v_name is null then raise exception 'product % not found in this shop', v_pid; end if;

    insert into bill_items(bill_id, shop_id, product_id, product_name, qty, unit_price, line_total)
    values (p_bill_id, p_shop_id, v_pid, v_name, v_qty, v_price, v_line);

    insert into stock_movements(shop_id, product_id, move_type, qty_change, ref_bill_id)
    values (p_shop_id, v_pid, 'sale', -v_qty, p_bill_id);

    update products set stock_qty = stock_qty - v_qty where id = v_pid and shop_id = p_shop_id;

    v_subtotal := v_subtotal + v_line;
  end loop;

  update bills set subtotal = v_subtotal, total = greatest(v_subtotal - p_discount, 0)
   where id = p_bill_id;

  if p_payment = 'credit' then
    if p_customer_id is null then raise exception 'credit sale needs a customer'; end if;
    insert into credit_ledger(shop_id, customer_id, amount, ref_bill_id)
    values (p_shop_id, p_customer_id, greatest(v_subtotal - p_discount, 0), p_bill_id);
  end if;

  return p_bill_id;
end $$;

revoke all on function create_shop(text, text) from public, anon;
revoke all on function create_bill(uuid, uuid, jsonb, uuid, payment_mode, numeric, text, timestamptz) from public, anon;
grant execute on function create_shop(text, text) to authenticated;
grant execute on function create_bill(uuid, uuid, jsonb, uuid, payment_mode, numeric, text, timestamptz) to authenticated;
